CREATE DATABASE IF NOT EXISTS lms_data;
USE lms_data;

CREATE TABLE IF NOT EXISTS root (
   id INT PRIMARY KEY,
   name VARCHAR(50),
   filename VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS college (
   id INT PRIMARY KEY,
   name VARCHAR(50),
   filename VARCHAR(50),
   root_id INT,
   FOREIGN KEY (root_id) REFERENCES root(id)
);

CREATE TABLE IF NOT EXISTS department (
   id INT PRIMARY KEY,
   name VARCHAR(50),
   filename VARCHAR(50),
   college_id INT,
   FOREIGN KEY (college_id) REFERENCES college(id)
);

CREATE TABLE IF NOT EXISTS lecture (
   id INT PRIMARY KEY,
   name VARCHAR(100),
   professor VARCHAR(50),
   credit INT,
   time VARCHAR(100),
   department_id INT,
   FOREIGN KEY (department_id) REFERENCES department(id)
);
SELECT * FROM root;  
SELECT * FROM college WHERE root_id = ?;
SELECT * FROM department WHERE college_id = ?;  
CREATE TABLE IF NOT EXISTS user (
   userid VARCHAR(50) PRIMARY KEY,
   name VARCHAR(50),
   code int,
   email VARCHAR(50),
   campus VARCHAR(50),
   college VARCHAR(50),
   department VARCHAR(50)
);

CREATE TABLE IF NOT EXISTS login (
    userId VARCHAR(50) PRIMARY KEY,
    password VARCHAR(50)
);
SELECT * FROM user;
CREATE TABLE IF NOT EXISTS save (
   userid VARCHAR(50),
   lecture_id INT,
   status VARCHAR(50),  
   PRIMARY KEY (userid, lecture_id, status), 
   FOREIGN KEY (userid) REFERENCES user(userid),
   FOREIGN KEY (lecture_id) REFERENCES lecture(id)
);
